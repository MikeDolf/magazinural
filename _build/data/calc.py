def _pts(prices):
    """{"3×4 м": 310000} → [(12, 310000)]: опорные точки из цен «от» популярных размеров."""
    out = []
    for dim, price in prices.items():
        w, l = dim.split(" м")[0].replace(",", ".").split("×")
        out.append((round(float(w) * float(l), 2), price))
    return sorted(out)


